import { CatalogRepository } from "../src/catalog/catalog-repository";
import assert from "node:assert/strict";
import { CatalogTestStorage, catalogTestDocument, catalogTestYaml, createCatalogTestRepository } from "./catalog-tests";
import { parseCatalogDocument } from "../src/catalog/catalog-document";

export async function runCatalogMigrationTests(): Promise<void> {
	const { repository, storage } = createCatalogTestRepository();
	const meetingPath = `${repository.paths.meetingsDir}/旧会议.md`;
	const sourcePath = "Transcripts/旧会议.transcript.md";
	const projectPath = `${repository.paths.projectsDir}/旧项目.md`;
	const meeting = catalogTestDocument({ echo_memory_type: "meeting", source: `[[${sourcePath}]]`, custom: ["保留"] }, "# 人工标题\n\n人工判断不可覆盖。\n<!-- echo-memory-meeting:start -->\n旧记忆链接\n<!-- echo-memory-meeting:end -->\n");
	const transcript = catalogTestDocument({ type: "audio-transcript", source_audio_path: "Audio/old.mp3", transcribed_at: "2026-11-07T00:00:00Z" }, "# 原始转写\n\n## 转写正文\n原文不可改写。\n");
	storage.files.set(meetingPath, meeting);
	storage.files.set(sourcePath, transcript);
	storage.files.set(projectPath, "# 旧项目\n\n人工背景\n");
	storage.files.set(repository.paths.memory.manifest, JSON.stringify({ runs: { run: { transcriptPath: sourcePath, meetingPath } }, entityIndex: { "project:旧项目": projectPath } }));
	const before = new Map(storage.files);
	const plan = await repository.dryRunMigration();
	assert.deepEqual(storage.files, before, "dry-run must not modify business files or write an identity registry");
	assert.equal(plan.issues.length, 0);
	assert.ok(plan.items.some((item) => item.path === sourcePath));
	const result = await repository.applyMigration(plan);
	assert.equal(result.conflicts.length, 0);
	const snapshot = await repository.snapshot();
	assert.equal(snapshot.meetings.length, 1);
	assert.equal(snapshot.projects.length, 1);
	assert.equal(snapshot.sources[0].meetingId, snapshot.meetings[0].id);
	assert.equal(snapshot.meetings[0].time.precision, "unknown", "transcribed_at must not become the meeting occurrence date");
	assert.match((await storage.read(meetingPath))!, /人工判断不可覆盖/);
	assert.deepEqual(parseCatalogDocument((await storage.read(meetingPath))!, catalogTestYaml).properties.custom, ["保留"]);
	const rerun = await repository.applyMigration(plan);
	assert.equal(rerun.written.length, 0);
	assert.equal(rerun.conflicts.length, 0);
	assert.equal((await repository.snapshot()).meetings[0].id, snapshot.meetings[0].id);
	const nextDryRun = await repository.dryRunMigration();
	assert.equal(nextDryRun.items.length, 0, "fresh dry-run after completion should be a no-op");
	assert.deepEqual(nextDryRun.issues, [], "transcript meeting foreign keys must not be mistaken for duplicate primary identities");
	storage.files.set(meetingPath, storage.files.get(meetingPath)! + "\n迁移之后人工继续编辑。\n");
	const rollback = await repository.rollbackMigration(plan.id);
	assert.ok(rollback.conflicts.some((item) => item.path === meetingPath));
	assert.match((await storage.read(meetingPath))!, /迁移之后人工继续编辑/);
	assert.equal(await storage.read(sourcePath), transcript);
	assert.equal(await storage.read(projectPath), "# 旧项目\n\n人工背景\n");

	const interrupted = createCatalogTestRepository();
	await interrupted.repository.initialize();
	interrupted.storage.files.set("Transcripts/new.transcript.md", catalogTestDocument({ type: "audio-transcript", source_audio_path: "Audio/new.mp3" }, "# New\n\n## 转写正文\n测试\n"));
	const interruptedPlan = await interrupted.repository.dryRunMigration();
	interrupted.storage.failPath = "Transcripts/new.transcript.md";
	const partial = await interrupted.repository.applyMigration(interruptedPlan);
	assert.ok(partial.conflicts.some((item) => item.path === "Transcripts/new.transcript.md"));
	interrupted.storage.failPath = null;
	const resumed = await interrupted.repository.applyMigration(interruptedPlan);
	assert.equal(resumed.conflicts.length, 0);
	assert.equal((await interrupted.repository.snapshot()).meetings.length, 1);
	assert.equal((await interrupted.repository.snapshot()).sources.length, 1);
	const copiedSource = (await interrupted.storage.read("Transcripts/new.transcript.md"))!;
	interrupted.storage.files.set("Transcripts/copy.transcript.md", copiedSource);
	const conflictPlan = await interrupted.repository.dryRunMigration();
	assert.ok(conflictPlan.issues.some((issue) => issue.code === "IDENTITY_CONFLICT"));

	const legacyEntry = createCatalogTestRepository();
	const oldMeetingPath = `${legacyEntry.repository.paths.meetingsDir}/原有会议.md`;
	const oldTranscriptPath = "Transcripts/existing.transcript.md";
	legacyEntry.storage.files.set(oldMeetingPath, catalogTestDocument({ echo_memory_type: "meeting", source: `[[${oldTranscriptPath}]]` }, "# 既有会议\n人工内容\n"));
	legacyEntry.storage.files.set(oldTranscriptPath, catalogTestDocument({ type: "audio-transcript", source_audio_path: "Audio/existing.mp3" }, "# 已有转写\n原文\n"));
	legacyEntry.storage.files.set(legacyEntry.repository.paths.memory.manifest, JSON.stringify({ runs: { old: { transcriptPath: oldTranscriptPath, meetingPath: oldMeetingPath } }, entityIndex: {} }));
	const adoptedSource = await legacyEntry.repository.registerTranscript({ transcriptPath: oldTranscriptPath, audioPath: "Audio/existing.mp3" });
	const audioMeeting = await legacyEntry.repository.ensureMeetingForAudio("Audio/existing.mp3");
	assert.equal(audioMeeting.id, adoptedSource.meetingId);
	assert.equal(audioMeeting.path, oldMeetingPath);
	assert.equal((await legacyEntry.repository.snapshot()).meetings.length, 1, "the normal audio entry path must adopt the reliable existing meeting before ensuring audio identity");
	assert.deepEqual((await legacyEntry.repository.dryRunMigration()).issues, []);

	const restartedStorage = new CatalogTestStorage();
	const restartedOptions = { storage: restartedStorage, yaml: catalogTestYaml, rootFolder: "Echo Memory", language: "zh" as const, transcriptFolders: ["Transcripts"] };
	const originalRepository = new CatalogRepository(restartedOptions);
	const restartSource = "Transcripts/restart.transcript.md";
	restartedStorage.files.set(restartSource, catalogTestDocument({ type: "audio-transcript", source_audio_path: "Audio/restart.mp3" }, "# Restart fixture\n原文\n"));
	const originalPlan = await originalRepository.dryRunMigration();
	restartedStorage.failPath = restartSource;
	const originalPartial = await originalRepository.applyMigration(originalPlan);
	assert.ok(originalPartial.conflicts.length);
	const meetingsBeforeRestart = await restartedStorage.list(originalRepository.paths.meetingsDir);
	assert.equal(meetingsBeforeRestart.length, 1);
	restartedStorage.failPath = null;
	const restartedRepository = new CatalogRepository(restartedOptions);
	await restartedRepository.initialize();
	assert.equal(await restartedStorage.read(restartedRepository.paths.registry), null, "opening the view during interrupted migration must not create an empty registry that invalidates its before-hash");
	const reopenedPlan = await restartedRepository.dryRunMigration();
	assert.equal(reopenedPlan.id, originalPlan.id, "a fresh dry-run after restart must reuse the unfinished persisted run");
	assert.deepEqual(reopenedPlan.items, originalPlan.items, "real random UUID allocation must not repeat after a partial write");
	await assert.rejects(restartedRepository.ensureMeetingForAudio("Audio/restart.mp3"), /迁移.*尚未完成/);
	const resumedAfterRestart = await restartedRepository.applyMigration(reopenedPlan);
	assert.deepEqual(resumedAfterRestart.conflicts, []);
	assert.deepEqual(await restartedStorage.list(restartedRepository.paths.meetingsDir), meetingsBeforeRestart);
	const resumedSnapshot = await restartedRepository.snapshot();
	assert.equal(resumedSnapshot.meetings.length, 1);
	assert.equal(resumedSnapshot.sources[0].meetingId, resumedSnapshot.meetings[0].id);
	assert.equal((await restartedRepository.dryRunMigration()).items.length, 0);

	const replayStorage = new CatalogTestStorage();
	const replayRepository = new CatalogRepository({ storage: replayStorage, yaml: catalogTestYaml, rootFolder: "Echo Memory", language: "zh", transcriptFolders: ["Transcripts"] });
	await replayRepository.initialize();
	const replaySource = "Transcripts/completed-run.transcript.md";
	replayStorage.files.set(replaySource, catalogTestDocument({ type: "audio-transcript", source_audio_path: "Audio/completed-run.mp3" }, "# Completed run\n人工原文\n"));
	const replayPlan = await replayRepository.dryRunMigration();
	assert.deepEqual((await replayRepository.applyMigration(replayPlan)).conflicts, []);
	const completedJournalPath = `${replayRepository.paths.migrationDir}/${replayPlan.id}/journal.json`;
	assert.equal((JSON.parse((await replayStorage.read(completedJournalPath))!) as { state: string }).state, "completed");
	await replayRepository.refreshProjections();
	const replayMeetingPath = (await replayRepository.snapshot()).meetings[0].path;
	replayStorage.files.set(replayMeetingPath, (await replayStorage.read(replayMeetingPath))! + "\n迁移完成后的人工补充。\n");
	replayStorage.files.set(replaySource, (await replayStorage.read(replaySource))! + "\n后续原文校对。\n");
	await replayRepository.ensureMeetingForAudio("Audio/new-after-completion.mp3", { title: "完成后新增会议" });
	const beforeCompletedReplay = new Map(replayStorage.files);
	const completedReplay = await replayRepository.applyMigration(replayPlan);
	assert.deepEqual(completedReplay.conflicts, [], "completed runs remain terminal after normal projections, edits and new registrations");
	assert.deepEqual(completedReplay.written, []);
	assert.equal(completedReplay.skipped.length, replayPlan.items.length);
	assert.deepEqual(replayStorage.files, beforeCompletedReplay, "replaying a completed run must not inspect-and-reclassify or overwrite subsequent business state");
	await replayRepository.ensureMeetingForAudio("Audio/business-continues.mp3", { title: "重放后继续业务" });
	assert.equal((await replayRepository.snapshot()).meetings.length, 3, "completed migration replay must not reactivate the global unfinished-migration gate");
	const completedJournal = JSON.parse((await replayStorage.read(completedJournalPath))!) as { state?: string };
	delete completedJournal.state;
	replayStorage.files.set(completedJournalPath, JSON.stringify(completedJournal));
	const legacyCompletedReplay = await replayRepository.applyMigration(replayPlan);
	assert.deepEqual(legacyCompletedReplay.conflicts, [], "older journals with all verified items must also be treated as completed terminal runs");
	await replayRepository.ensureMeetingForAudio("Audio/legacy-journal-continues.mp3");

	const changed = createCatalogTestRepository();
	changed.storage.files.set("Transcripts/change.transcript.md", catalogTestDocument({ type: "audio-transcript" }, "# Change\n正文\n"));
	const stale = await changed.repository.dryRunMigration();
	changed.storage.files.set("Transcripts/change.transcript.md", "# 已改写\n保留这次修改\n");
	const staleResult = await changed.repository.applyMigration(stale);
	assert.ok(staleResult.conflicts.length);
	assert.equal(await changed.storage.read("Transcripts/change.transcript.md"), "# 已改写\n保留这次修改\n");
	console.log("Catalog migration dry-run, idempotence, conflict and protected rollback tests passed.");
}
